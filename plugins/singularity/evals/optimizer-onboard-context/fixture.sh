// Order totals. Amounts are integer cents; never use floats for money.
export function total(lines, discountPercent = 0) {
  const gross = lines.reduce((sum, l) => sum + l.unitCents * l.qty, 0)
  return gross - Math.floor((gross * discountPercent) / 100)
}
EOF
